"""Render frozen validation diagnostics, never fit or run a world model.

Inputs: animation_inputs.npz + animation_meta.json from the frozen diagnostic.
The left column uses saved true RGB exactly (nearest-neighbor enlargement).
The middle column is re-encoded observation reconstruction, NOT prediction.
Only the right column is autonomous rollout. Decoded columns are redrawings
through the frozen smooth_v1 renderer, not images generated by the world model.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont


HERE = Path(__file__).resolve().parent
COLORS = ("#2862AF", "#24765B", "#BB5327")
INK, MUTED, BG = "#183049", "#4D6176", "#F4F7FB"
W, HEADER, FOOTER = 930, 198, 82


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def font_path(explicit=None):
    candidates = ([Path(explicit)] if explicit else []) + [
        Path("/System/Library/Fonts/STHeiti Medium.ttc"),
        Path("/System/Library/Fonts/Hiragino Sans GB.ttc"),
        Path("/System/Library/Fonts/PingFang.ttc"),
        Path("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"),
    ]
    for path in candidates:
        if path.is_file():
            return path
    raise FileNotFoundError("A Chinese font is required; pass --font with a CJK TTF/TTC path")


def load_renderer(code_root):
    path = Path(code_root) / "dpbench/generate.py"
    if not path.is_file():
        raise FileNotFoundError(f"Frozen renderer not found: {path}")
    spec = importlib.util.spec_from_file_location("animation_frozen_renderer", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.render, path


def validate_arrays(arrays, meta):
    required = {"true_rgb", "truth", "teacher_prediction", "autonomous_prediction",
                "time", "valid_steps", "energy_band", "group_id", "episode"}
    missing = required - set(arrays)
    if missing:
        raise ValueError(f"Missing animation fields: {sorted(missing)}")
    if arrays["true_rgb"].shape != (4, 33, 64, 64, 3) or arrays["true_rgb"].dtype != np.uint8:
        raise ValueError("true_rgb must be the four saved 33-frame uint8 RGB clips, shape [4,33,64,64,3]")
    for key in ("truth", "teacher_prediction", "autonomous_prediction"):
        if arrays[key].shape != (4, 33, 2):
            raise ValueError(f"{key} must have shape [4,33,2]")
    if not np.isfinite(arrays["truth"]).all():
        raise ValueError("Reference truth contains invalid states")
    if arrays["time"].shape != (33,) or not np.allclose(arrays["time"], np.arange(33) * .1, atol=1e-8, rtol=0):
        raise ValueError("This visualization requires original dt=.1, relative time 0..3.2; no resampling")
    for key in ("valid_steps", "energy_band", "group_id", "episode"):
        if arrays[key].shape != (4,):
            raise ValueError(f"{key} must have four entries")
    if sorted(arrays["energy_band"].tolist()) != [0, 1, 2, 3]:
        raise ValueError("Exactly one case from each of energy bands 0,1,2,3 is required")
    valid = arrays["valid_steps"]
    if not np.issubdtype(valid.dtype, np.integer) or np.any(valid < 0) or np.any(valid > 32):
        raise ValueError("valid_steps must count 0..32 valid transitions per case")
    if not isinstance(meta.get("readout_quality_passed"), bool):
        raise ValueError("Metadata must declare readout_quality_passed as a boolean")
    if not isinstance(meta.get("checkpoint_step"), int):
        raise ValueError("Metadata must declare the actual checkpoint_step")
    # Cross-check identity when the producer supplies its selected-record table.
    records = meta.get("selected_records", [])
    if records:
        identities = {(int(r["energy_band"]), int(r["group_id"]), int(r["episode"])) for r in records}
        expected = set(zip(arrays["energy_band"].tolist(), arrays["group_id"].tolist(), arrays["episode"].tolist()))
        if identities != expected:
            raise ValueError("Selected-record metadata disagrees with NPZ identities")


def center(draw, text, x, y, font, color=INK):
    box = draw.textbbox((0, 0), text, font=font)
    draw.text((x - (box[2] - box[0]) / 2, y), text, font=font, fill=color)


def quality_text(meta):
    if meta["readout_quality_passed"]:
        return "读出诊断通过；中列为逐帧重建，不是预测。右列仍需独立物理验收。", "#E5F2E9", "#235F40"
    return "读出未达标：仅作诊断，不代表物理预测验收。中列不是预测。", "#FFF0DD", "#904A16"


def metric_text(meta):
    quality = meta.get("teacher_readout_quality", {})
    # Only display metrics explicitly present; do not infer units or invented values.
    if not isinstance(quality, dict):
        quality = {}
    angle = quality.get("angle_rmse_rad")
    omega = quality.get("omega_rmse_rad_s")
    text = f"冻结读出：{meta.get('selected_readout', '未注明')}"
    if isinstance(angle, (int, float)) and np.isfinite(angle):
        text += f"   逐帧重建角度 RMSE {angle:.3f} rad"
    if isinstance(omega, (int, float)) and np.isfinite(omega):
        text += f"   角速度 {omega:.3f} rad/s"
    return text


def frame_image(k, selected, arrays, meta, renderer, fontfile, *, single=False):
    row_height, image_size = (300, 240) if single else (220, 160)
    height = HEADER + row_height * len(selected) + FOOTER
    image = Image.new("RGB", (W, height), BG)
    draw = ImageDraw.Draw(image)
    fonts = {n: ImageFont.truetype(str(fontfile), n) for n in (18, 20, 22, 27)}
    synthetic = meta.get("synthetic_layout_check", False)
    title = "SYNTHETIC · 仅排版检查" if synthetic else f"无阻尼阶段 A · {meta['checkpoint_step']} 步"
    draw.text((24, 16), title, font=fonts[27], fill=INK)
    center(draw, f"t = {arrays['time'][k]:.1f} / 3.2 秒", 766, 18, fonts[22])
    checkpoint_hash = str(meta.get("checkpoint_sha256", "未提供"))[:12]
    line = f"D = 0 · 冻结检查点 {checkpoint_hash} · 验证集诊断 · 播放速度 1×"
    if synthetic:
        line = "此图使用合成测试数据，仅检查排版与 INVALID 显示；不是训练结果。"
    draw.text((24, 54), line, font=fonts[18], fill=MUTED)
    draw.text((24, 81), metric_text(meta), font=fonts[18], fill=MUTED)
    text, banner, textcolor = quality_text(meta)
    draw.rounded_rectangle((20, 109, W - 20, 139), radius=7, fill=banner)
    draw.text((29, 114), text, font=fonts[18], fill=textcolor)
    xs = [24 + j * 298 for j in range(3)]
    width = 286
    labels = ("真实 RGB", "逐帧编码重建", "自主预测")
    subtitles = ("原始帧，仅放大", "逐帧看真实图像 · 非预测", "仅用起始 21 帧初始化")
    for j in range(3):
        center(draw, labels[j], xs[j] + width / 2, 149, fonts[22], COLORS[j])
        center(draw, subtitles[j], xs[j] + width / 2, 176, fonts[18], MUTED)
    for row, i in enumerate(selected):
        y = HEADER + row_height * row
        draw.text((25, y + 1), f"能量层 {arrays['energy_band'][i]}   ·   group {arrays['group_id'][i]}   ·   episode {arrays['episode'][i]}",
                  font=fonts[18], fill=INK)
        for col, key in enumerate(("truth", "teacher_prediction", "autonomous_prediction")):
            x = xs[col]
            draw.rounded_rectangle((x, y + 24, x + width, y + row_height - 4), radius=8, fill="white", outline=COLORS[col], width=2)
            theta, omega = arrays[key][i, k]
            valid = np.isfinite(theta) and np.isfinite(omega)
            if col == 2:
                valid = valid and k <= int(arrays["valid_steps"][i])
            if col == 0:
                rgb = arrays["true_rgb"][i, k]  # Never redraw the reference image from the state.
            elif valid:
                rgb = renderer(float(theta), 64, renderer="smooth_v1")
            else:
                rgb = None
            if rgb is not None:
                tile = Image.fromarray(rgb).resize((image_size, image_size), Image.Resampling.NEAREST)
                image.paste(tile, (int(x + (width - image_size) / 2), y + 29))
                text = f"θ {theta:+.2f} rad   ω {omega:+.2f}"
                center(draw, text, x + width / 2, y + row_height - 28, fonts[18], MUTED)
            else:
                draw.rectangle((x + 10, y + 35, x + width - 10, y + row_height - 35), fill="#FFF1EF")
                center(draw, "INVALID", x + width / 2, y + 75, fonts[27], "#A9332C")
                center(draw, "求解失败或非有限读出", x + width / 2, y + 116, fonts[18], "#A9332C")
                center(draw, "未补帧、未沿用上一帧", x + width / 2, y + 144, fonts[18], "#A9332C")
    footer_y = HEADER + row_height * len(selected)
    draw.text((24, footer_y + 10), "固定样本：每层最小 group_id，不按误差筛选。单位：θ rad、ω rad/s。", font=fonts[18], fill=MUTED)
    draw.text((24, footer_y + 37), "θ=0 向下、正角向右；同一相机。时间从观察终点算起，每 0.1 秒一帧，无插值。", font=fonts[18], fill=MUTED)
    draw.rectangle((24, height - 10, W - 24, height - 6), fill="#DBE3EE")
    draw.rectangle((24, height - 10, 24 + (W - 48) * k / 32, height - 6), fill=COLORS[2])
    return image


def save_gif(frames, path):
    # A palette sampled across time keeps the static labels and dynamic RGB
    # colors stable; never interpolate or synthesize intermediate states.
    strip = Image.new("RGB", (frames[0].width, frames[0].height * 3))
    for i, frame in enumerate((frames[0], frames[16], frames[-1])):
        strip.paste(frame, (0, i * frame.height))
    palette = strip.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    indexed = [frame.quantize(palette=palette, dither=Image.Dither.NONE) for frame in frames]
    indexed[0].save(path, save_all=True, append_images=indexed[1:], duration=100, loop=0, optimize=False, disposal=2)


def render_bundle(arrays, meta, output, code_root, *, font=None, single_cases=False, inputs=None):
    validate_arrays(arrays, meta)
    output = Path(output)
    if output.exists() and any(output.iterdir()):
        raise FileExistsError(f"Refusing to mix render outputs with a nonempty directory: {output}")
    output.mkdir(parents=True, exist_ok=True)
    renderer, renderer_path = load_renderer(code_root)
    fontfile = font_path(font)
    selected = np.argsort(arrays["energy_band"]).tolist()
    frames = [frame_image(k, selected, arrays, meta, renderer, fontfile) for k in range(33)]
    save_gif(frames, output / "comparison.gif")
    frames[16].save(output / "preview.png")
    outputs = ["comparison.gif", "preview.png"]
    if single_cases:
        for i in (selected[0], selected[-1]):
            name = f"single_band{int(arrays['energy_band'][i])}.gif"
            save_gif([frame_image(k, [i], arrays, meta, renderer, fontfile, single=True) for k in range(33)], output / name)
            outputs.append(name)
    with Image.open(output / "comparison.gif") as saved:
        if saved.n_frames != 33 or saved.size != (W, HEADER + 4 * 220 + FOOTER):
            raise RuntimeError("Saved animation frame count/dimensions differ from requested layout")
    manifest = {"kind": "SYNTHETIC_LAYOUT_CHECK_NOT_TRAINING_RESULT" if meta.get("synthetic_layout_check") else "frozen_validation_animation",
                "checkpoint_step": meta["checkpoint_step"], "readout_quality_passed": meta["readout_quality_passed"],
                "dimensions": list(frames[0].size), "frames": 33, "duration_ms_per_frame": 100,
                "relative_time_seconds": [0., 3.2], "preview_time_seconds": 1.6,
                "selection": "One preselected validation case per energy band, smallest group_id; not error-based",
                "cases": [{key: int(arrays[key][i]) for key in ("energy_band", "group_id", "episode", "valid_steps")} for i in selected],
                "columns": ["saved_true_RGB", "per_frame_reencoded_readout_NOT_prediction", "autonomous_readout_redrawn"],
                "geometry": "Frozen smooth_v1 renderer: pivot=size/2, rod_length=.36*size; x=sin(theta), y=cos(theta)",
                "quantization": "True RGB only nearest-neighbor enlarged; GIF palette quantizes display colors. No state/time interpolation.",
                "font": str(fontfile), "renderer_sha256": sha(renderer_path), "script_sha256": sha(__file__),
                "source_sha256": {str(path): sha(path) for path in (inputs or [])},
                "outputs": {name: {"sha256": sha(output / name), "bytes": (output / name).stat().st_size} for name in outputs}}
    (output / "render_manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    return manifest


def synthetic_arrays(code_root):
    """CPU-only layout fixture with deliberate invalid suffix; never model data."""
    renderer, _ = load_renderer(code_root)
    time = np.arange(33) * .1
    truth = np.stack([np.column_stack((a * np.cos(3 * time), -3 * a * np.sin(3 * time))) for a in (.2, .6, 1.1, 1.8)])
    rgb = np.stack([[renderer(float(theta), renderer="smooth_v1") for theta in case[:, 0]] for case in truth])
    teacher = truth.copy(); teacher[..., 0] += .02
    prediction = truth.copy(); prediction[..., 0] *= .8
    prediction[3, 21:] = np.nan
    arrays = dict(true_rgb=rgb, truth=truth, teacher_prediction=teacher, autonomous_prediction=prediction,
                  time=time, valid_steps=np.array([32, 32, 32, 20]), energy_band=np.arange(4),
                  group_id=np.arange(100, 104), episode=np.arange(4))
    meta = dict(checkpoint_step=4000, checkpoint_sha256="SYNTHETIC-NOT-REAL", selected_readout="synthetic",
                readout_quality_passed=False, synthetic_layout_check=True)
    return arrays, meta


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path)
    parser.add_argument("--metadata", type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--code-root", type=Path, default=HERE / "frozen_code")
    parser.add_argument("--font", type=Path)
    parser.add_argument("--single-cases", action="store_true")
    parser.add_argument("--self-test", action="store_true", help="Render visibly labeled synthetic layout fixture only")
    args = parser.parse_args(argv)
    if args.self_test:
        if args.inputs or args.metadata:
            parser.error("--self-test must not be combined with real input files")
        arrays, meta = synthetic_arrays(args.code_root)
        inputs = []
    else:
        if args.inputs is None or args.metadata is None:
            parser.error("Real rendering requires --inputs and --metadata")
        with np.load(args.inputs, allow_pickle=False) as handle:
            arrays = {key: handle[key] for key in handle.files}
        meta = json.loads(args.metadata.read_text())
        inputs = [args.inputs, args.metadata]
    result = render_bundle(arrays, meta, args.output_dir, args.code_root, font=args.font,
                           single_cases=args.single_cases, inputs=inputs)
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return result


if __name__ == "__main__":
    main()
