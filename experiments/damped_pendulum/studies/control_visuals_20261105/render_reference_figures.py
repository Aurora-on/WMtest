#!/usr/bin/env python3
"""Render current control-step10000 diagnostics from frozen evaluation arrays.

The first row uses actual stored RGB, never redrawn ground truth. The other
rows are state-readout redrawings, not images generated by the world model.
No fitting, model loading, future conditioning, or trajectory interpolation.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont


HERE = Path(__file__).resolve().parent
INK, MUTED, BG = "#183049", "#506174", "#F4F7FB"
COLORS = ("#2862AF", "#278065", "#BB5327")
KEYS = ("truth", "teacher_prediction", "autonomous_prediction")
LABELS = ("真实视频", "逐时刻重建", "自主预测")
FONT_CANDIDATES = (
    "/System/Library/Fonts/STHeiti Medium.ttc",
    "/System/Library/Fonts/Hiragino Sans GB.ttc",
    "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def font_file(explicit=None):
    for candidate in ([explicit] if explicit else []) + list(FONT_CANDIDATES):
        if Path(candidate).is_file():
            return Path(candidate)
    raise FileNotFoundError("Specify a Chinese TTF/TTC font with --font")


def renderer_from(code_root):
    path = Path(code_root) / "dpbench/generate.py"
    spec = importlib.util.spec_from_file_location("control_frozen_renderer", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.render, path


def validate(arrays, meta):
    if meta.get("checkpoint_step") != 10000:
        raise ValueError("This delivery requires the current control step10000 checkpoint")
    if meta.get("experiment_arm") != "control":
        raise ValueError("This delivery requires explicit control-arm provenance")
    if not isinstance(meta.get("readout_quality_passed"), bool):
        raise ValueError("Readout quality must be explicitly supplied")
    if not isinstance(meta.get("checkpoint_sha256"), str) or len(meta["checkpoint_sha256"]) != 64:
        raise ValueError("The frozen checkpoint SHA256 is required")
    if arrays["true_rgb"].shape != (4, 33, 64, 64, 3) or arrays["true_rgb"].dtype != np.uint8:
        raise ValueError("Expected four actual 33-frame RGB clips")
    for key in KEYS:
        if arrays[key].shape != (4, 33, 2):
            raise ValueError(f"Invalid {key} shape")
    if not np.isfinite(arrays["truth"]).all():
        raise ValueError("Nonfinite reference state")
    if not np.allclose(arrays["time"], np.arange(33) * .1, rtol=0, atol=1e-8):
        raise ValueError("Expected original 0.1-second sampling, no interpolation")
    if sorted(arrays["energy_band"].tolist()) != [0, 1, 2, 3]:
        raise ValueError("Expected one sample from each initial energy band")
    ids = {(int(r["energy_band"]), int(r["group_id"]), int(r["episode"]))
           for r in meta["selected_records"]}
    if ids != set(zip(arrays["energy_band"].tolist(), arrays["group_id"].tolist(), arrays["episode"].tolist())):
        raise ValueError("Metadata and array identities disagree")
    valid = arrays["valid_steps"]
    if not np.issubdtype(valid.dtype, np.integer) or np.any(valid < 0) or np.any(valid > 32):
        raise ValueError("Invalid valid_steps")


def center(draw, text, x, y, font, fill=INK):
    box = draw.textbbox((0, 0), text, font=font)
    draw.text((x - (box[2] - box[0]) / 2, y), text, font=font, fill=fill)


def banner(draw, box, meta, font):
    passed = meta["readout_quality_passed"]
    fill = "#E5F2E9" if passed else "#FFF0DD"
    ink = "#235F40" if passed else "#904A16"
    text = ("读出诊断通过；逐时刻重建不是预测，自主预测仍需独立评估。" if passed else
            "读出诊断未通过：摆图包含表示／读出误差，不能单独归因于动力学。")
    draw.rounded_rectangle(box, radius=8, fill=fill)
    draw.text((box[0] + 12, box[1] + 8), text, font=font, fill=ink)


def rgb_at(arrays, case, step, column, renderer):
    if column == 0:
        return arrays["true_rgb"][case, step]
    state = arrays[KEYS[column]][case, step]
    if not np.isfinite(state).all() or (column == 2 and step > arrays["valid_steps"][case]):
        return None
    return renderer(float(state[0]), 64, renderer="smooth_v1")


def paste_rgb(image, draw, rgb, box, *, size, font):
    x0, y0, x1, y1 = box
    if rgb is None:
        draw.rounded_rectangle(box, radius=5, fill="#FFF1EF")
        center(draw, "INVALID", (x0 + x1) / 2, y0 + size / 2 - 12, font, "#A9332C")
    else:
        tile = Image.fromarray(rgb).resize((size, size), Image.Resampling.NEAREST)
        image.paste(tile, (round((x0 + x1 - size) / 2), round(y0)))


def filmstrip(arrays, meta, case, renderer, fontpath):
    width, height = 1400, 930
    image = Image.new("RGB", (width, height), BG)
    draw = ImageDraw.Draw(image)
    fonts = {n: ImageFont.truetype(str(fontpath), n) for n in (20, 21, 23, 25, 32)}
    band, ep, group = (int(arrays[k][case]) for k in ("energy_band", "episode", "group_id"))
    draw.text((28, 18), f"对照组 · 10000步 · 无阻尼    |    初始能量层 {band}", font=fonts[32], fill=INK)
    draw.text((28, 63), f"验证集 episode {ep} · group {group}   |   t=0 为起始21帧观测的末端", font=fonts[21], fill=MUTED)
    banner(draw, (24, 100, width - 24, 143), meta, fonts[21])
    steps = [0, 8, 16, 24, 32]
    left, cell, start_y, row_height = 235, 225, 192, 211
    for col, step in enumerate(steps):
        center(draw, f"t = {arrays['time'][step]:.1f} 秒", left + (col + .5) * cell, 160, fonts[23])
    row_notes = (("保存的原始图像", "仅作最近邻放大"),
                 ("每步重读真实视频", "诊断用 · 不是预测"),
                 ("仅用起始21帧", "之后不再看真实图像"))
    for row, key in enumerate(KEYS):
        top = start_y + row * row_height
        draw.rounded_rectangle((20, top, width - 20, top + row_height - 10), radius=10, fill="white")
        draw.text((34, top + 49), LABELS[row], font=fonts[25], fill=COLORS[row])
        for j, note in enumerate(row_notes[row]):
            draw.text((34, top + 91 + j * 28), note, font=fonts[20], fill=MUTED)
        for col, step in enumerate(steps):
            x = left + col * cell
            paste_rgb(image, draw, rgb_at(arrays, case, step, row, renderer), (x, top + 8, x + cell, top + 168), size=160, font=fonts[25])
            theta = arrays[key][case, step, 0]
            good = np.isfinite(theta) and (row != 2 or step <= arrays["valid_steps"][case])
            value = f"θ = {theta:+.2f} rad" if good else "无有效结果，未补帧"
            center(draw, value, x + cell / 2, top + 170, fonts[20], COLORS[row])
    draw.text((28, 839), "选样：每个初始能量层的最小 group_id；不按误差筛选。θ=0 向下，正角向右。", font=fonts[20], fill=MUTED)
    draw.text((28, 868), "重建／预测均由潜状态经固定读出后重绘；模型并不直接生成这些摆图。", font=fonts[20], fill=MUTED)
    draw.text((28, 897), f"检查点 SHA256：{meta['checkpoint_sha256'][:20]}…   |   原始间隔0.1秒，无插值", font=fonts[20], fill=MUTED)
    return image


def curve_figure(arrays, meta, path, fontpath):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.font_manager import FontProperties
    font = FontProperties(fname=str(fontpath))
    fig, axes = plt.subplots(2, 2, figsize=(12.8, 8.8), sharex=True, sharey=True)
    for ax, case in zip(axes.flat, np.argsort(arrays["energy_band"])):
        for col, key in enumerate(KEYS):
            angle = arrays[key][case, :, 0].copy()
            angle = np.arctan2(np.sin(angle), np.cos(angle))
            if col == 2:
                angle[int(arrays["valid_steps"][case]) + 1:] = np.nan
            # Avoid drawing a spurious line across the circular angle boundary.
            jumps = np.flatnonzero(np.abs(np.diff(angle)) > np.pi) + 1
            angle[jumps] = np.nan
            ax.plot(arrays["time"], angle, color=COLORS[col], lw=2.3 if col == 0 else 1.8,
                    linestyle=("-", "--", "-")[col], label=("真实角度（参考）" if col == 0 else LABELS[col]))
        ax.set_title(f"能量层 {int(arrays['energy_band'][case])} · episode {int(arrays['episode'][case])}", fontproperties=font, fontsize=13)
        ax.set_xlim(0, 3.2); ax.set_ylim(-np.pi, np.pi)
        ax.set_xticks([0, .8, 1.6, 2.4, 3.2]); ax.set_yticks([-np.pi, 0, np.pi], ["−π", "0", "π"])
        ax.grid(alpha=.2)
        ax.set_xlabel("自主预测时间（秒）", fontproperties=font, fontsize=11)
        ax.set_ylabel("角度（rad）", fontproperties=font, fontsize=11)
    handles, labels = axes.flat[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", bbox_to_anchor=(.5, .945), ncol=3, prop=font, frameon=False)
    fig.suptitle("对照组 · 10000步 · 无阻尼：四个固定样本的角度轨迹", fontproperties=font, fontsize=19, y=.988)
    footer = "虚线：每步重新观察真实视频后的读出，不是预测。重建与预测曲线均包含读出误差。"
    if not meta["readout_quality_passed"]:
        footer += "\n读出诊断未通过：不能仅凭曲线将全部误差归因于动力学。"
    fig.text(.5, .035, footer, ha="center", va="center", fontproperties=font, fontsize=11, color=MUTED)
    fig.subplots_adjust(left=.08, right=.98, top=.86, bottom=.13, hspace=.35, wspace=.18)
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)


def movie_frame(arrays, meta, step, renderer, fontpath):
    width, height = 1050, 810
    image = Image.new("RGB", (width, height), BG); draw = ImageDraw.Draw(image)
    fonts = {n: ImageFont.truetype(str(fontpath), n) for n in (18, 20, 23, 28)}
    draw.text((22, 14), "对照组 · 10000步 · 无阻尼", font=fonts[28], fill=INK)
    draw.text((760, 20), f"t = {arrays['time'][step]:.1f} / 3.2 秒", font=fonts[23], fill=INK)
    banner(draw, (18, 56, width - 18, 97), meta, fonts[20])
    ordered = np.argsort(arrays["energy_band"]); selected = (ordered[0], ordered[-1])
    for col, label in enumerate(LABELS):
        center(draw, label, 175 + 350 * col, 109, fonts[23], COLORS[col])
        center(draw, ("原始图像", "每步看真实视频 · 非预测", "仅用起始21帧初始化")[col], 175 + 350 * col, 142, fonts[18], MUTED)
    for row, case in enumerate(selected):
        top = 180 + row * 270
        draw.text((26, top), f"能量层 {int(arrays['energy_band'][case])} · episode {int(arrays['episode'][case])}", font=fonts[20], fill=INK)
        for col, key in enumerate(KEYS):
            x = 350 * col
            paste_rgb(image, draw, rgb_at(arrays, case, step, col, renderer), (x, top + 30, x + 350, top + 222), size=192, font=fonts[28])
            theta = arrays[key][case, step, 0]
            good = np.isfinite(theta) and (col != 2 or step <= arrays["valid_steps"][case])
            center(draw, f"θ = {theta:+.2f} rad" if good else "INVALID · 未补帧", x + 175, top + 230, fonts[20], COLORS[col])
    draw.text((24, 735), "固定样本：最低／最高能量层各取最小 group_id。播放1×；每0.1秒一帧。", font=fonts[18], fill=MUTED)
    draw.text((24, 764), "重建／预测是固定状态读出后的重绘，不是模型直接生成的图像。", font=fonts[18], fill=MUTED)
    return image


def save_movie(arrays, meta, renderer, fontpath, output):
    frames = [movie_frame(arrays, meta, k, renderer, fontpath) for k in range(33)]
    strip = Image.new("RGB", (frames[0].width, 3 * frames[0].height))
    for j, k in enumerate((0, 16, 32)):
        strip.paste(frames[k], (0, j * frames[0].height))
    palette = strip.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
    indexed = [f.quantize(palette=palette, dither=Image.Dither.NONE) for f in frames]
    indexed[0].save(output, save_all=True, append_images=indexed[1:], loop=0, duration=100, optimize=False, disposal=2)
    with Image.open(output) as saved:
        if saved.n_frames != 33:
            raise RuntimeError("Animation frame count differs from original sequence")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evaluation-dir", type=Path, default=HERE / "evaluation")
    parser.add_argument("--output-dir", type=Path, default=HERE / "figures")
    parser.add_argument("--code-root", type=Path, required=True)
    parser.add_argument("--font")
    parser.add_argument("--gif", action="store_true")
    args = parser.parse_args(argv)
    if args.output_dir.exists() and any(args.output_dir.iterdir()):
        raise FileExistsError("Output directory must be empty to avoid mixing different checkpoints")
    source = args.evaluation_dir / "animation_inputs.npz"
    metadata = args.evaluation_dir / "animation_meta.json"
    with np.load(source, allow_pickle=False) as handle:
        arrays = {key: handle[key] for key in handle.files}
    meta = json.loads(metadata.read_text()); validate(arrays, meta)
    renderer, renderer_path = renderer_from(args.code_root)
    fontpath = font_file(args.font)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs = []
    for case in np.argsort(arrays["energy_band"]):
        filename = f"control10000_band{int(arrays['energy_band'][case])}_frames.png"
        filmstrip(arrays, meta, case, renderer, fontpath).save(args.output_dir / filename)
        outputs.append(filename)
    curve_figure(arrays, meta, args.output_dir / "control10000_angle_curves.png", fontpath)
    outputs.append("control10000_angle_curves.png")
    if args.gif:
        save_movie(arrays, meta, renderer, fontpath, args.output_dir / "control10000_comparison.gif")
        outputs.append("control10000_comparison.gif")
    manifest = dict(kind="control10000_frozen_validation_diagnostic", checkpoint_step=meta["checkpoint_step"],
        checkpoint_sha256=meta["checkpoint_sha256"], readout_quality_passed=meta["readout_quality_passed"],
        selected_records=meta["selected_records"], selection="Minimum group_id per initial-energy band; no error-based selection",
        static_frame_steps=[0, 8, 16, 24, 32], static_relative_times=[0., .8, 1.6, 2.4, 3.2],
        source_sha256={str(source):sha(source), str(metadata):sha(metadata)},
        script_sha256=sha(__file__), renderer_sha256=sha(renderer_path), font=str(fontpath),
        display="Ground-truth uses stored RGB enlarged by nearest-neighbor. Other rows use fixed state-readout redrawings. No interpolation.",
        curves="Circular angles in [-pi,pi]; lines break at branch-cut crossings. Invalid predicted suffixes remain absent.",
        outputs={name:dict(sha256=sha(args.output_dir/name), bytes=(args.output_dir/name).stat().st_size) for name in outputs})
    (args.output_dir / "render_manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(dict(output_dir=str(args.output_dir.resolve()), outputs=outputs), ensure_ascii=False))


if __name__ == "__main__":
    main()
